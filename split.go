var pyprojectLintTools = map[string]bool{
	"ruff": true, "mypy": true, "pyright": true, "pylint": true,
	"flake8": true, "bandit": true, "codespell": true,
}

func isLintConfig(filePath string) bool {
	p := strings.ReplaceAll(filePath, "\\", "/")
	if strings.HasPrefix(p, ".github/workflows/") || strings.Contains(p, "/.github/workflows/") {
		return false
	}
	return lintConfigNames[strings.ToLower(path.Base(p))]
}

var tomlSectionHeaderRe = regexp.MustCompile(`^\[{1,2}\s*([A-Za-z0-9_-]+(?:\s*\.\s*(?:[A-Za-z0-9_-]+|"[^"\n]+"|'[^'\n]+'))*)\s*\]{1,2}(?:\s*#.*)?$`)

func pyprojectToolSection(line string) (string, bool) {
	m := tomlSectionHeaderRe.FindStringSubmatch(strings.TrimSpace(line))
	if m == nil {
		return "", false
	}
	return m[1], true
}

func isPyprojectLintTool(section string) bool {
	rest, ok := strings.CutPrefix(strings.ToLower(section), "tool.")
	if !ok {
		return false
	}
	name, _, _ := strings.Cut(rest, ".")
	return pyprojectLintTools[name]
}

// pyprojectLintUnits emits one line-aligned LintConfig unit per contiguous linter/typechecker [tool.*] run.
func pyprojectLintUnits(filePath string, src []byte) []Unit {
	lines := strings.Split(strings.TrimRight(string(src), "\n"), "\n")
	var units []Unit
	var cur []string
	start := 0
	flush := func() {
		for len(cur) > 0 && strings.TrimSpace(cur[len(cur)-1]) == "" {
			cur = cur[:len(cur)-1]
		}
		if len(cur) > 0 {
			units = append(units, Unit{Kind: "LintConfig", File: filePath, Start: start, End: start + len(cur) - 1, Text: strings.Join(cur, "\n")})
		}
		cur, start = nil, 0
	}
	inTool := false
	for i, line := range lines {
		if sec, ok := pyprojectToolSection(line); ok {
			next := isPyprojectLintTool(sec)
			if inTool && !next {
				flush()
			}
			inTool = next
		}
		if !inTool {
			continue
		}
		if start == 0 {
			start = i + 1
		}
		cur = append(cur, line)
	}
	flush()
	return units
}

var generatedBannerRe = regexp.MustCompile(`(?i)(?:generated[^\n]*\bdo not edit\b|\bdo not edit\b[^\n]*generated|automatically generated|generated automatically|auto[- ]?generated|^[/*#!\s]*(?:note:?\s+|caution:?\s+)?generated by\b|@generated\b)`)

// isGeneratedFile reports whether the leading comment header declares the file auto-generated.
func isGeneratedFile(src []byte) bool {
	limit := min(len(src), 2048)
	checked := 0
	for line := range strings.SplitSeq(string(src[:limit]), "\n") {
		t := strings.TrimSpace(line)
		if t == "" {
			continue
		}
		checked++
		if checked > 15 {
			break
		}
		isComment := strings.HasPrefix(t, "//") || strings.HasPrefix(t, "/*") || strings.HasPrefix(t, "*") || strings.HasPrefix(t, "#")
		if isComment && generatedBannerRe.MatchString(t) {
			return true
		}
	}
	return false
}

func splitFile(filePath string, src []byte) []Unit {
	ext := extOf(filePath)
	var units []Unit
	if isLintConfig(filePath) {
		if strings.EqualFold(path.Base(strings.ReplaceAll(filePath, "\\", "/")), "pyproject.toml") {
			return pyprojectLintUnits(filePath, src)
		}
		if text := strings.TrimRight(string(src), "\n"); strings.TrimSpace(text) != "" {
			units = append(units, Unit{Kind: "LintConfig", File: filePath, Start: 1, End: strings.Count(text, "\n") + 1, Text: text})
		}
		// JS/TS linter configs also run through tree-sitter so default-on comment/file rules keep covering them.
		if key, ok := tsExt[ext]; ok {
			units = append(units, attachTestHelpers(splitTree(filePath, src, tsLangs[key]))...)
		}
		return units
	}
	switch ext {
	case ".md", ".markdown":
		return splitMarkdown(filePath, src)
	case ".go":
		if isGeneratedFile(src) {
			return nil
		}
		return attachTestHelpers(splitGo(filePath, src))
	}
	if key, ok := tsExt[ext]; ok {
		if isGeneratedFile(src) {
			return nil
		}
		return attachTestHelpers(splitTree(filePath, src, tsLangs[key]))
	}
	if ext == "" && isShellShebang(src) {
		if isGeneratedFile(src) {
			return nil
		}
		return attachTestHelpers(splitTree(filePath, src, tsLangs["sh"]))
	}
	return nil
}

func extOf(filePath string) string {
	base := path.Base(filePath)
	i := strings.LastIndex(base, ".")
	if i <= 0 {
		return ""
	}
	return strings.ToLower(base[i:])
}

func splitGo(path string, src []byte) []Unit {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, path, src, parser.ParseComments)
	if err != nil {
		fmt.Fprintf(os.Stderr, "warn: %s: %v (skipped)\n", path, err)
		return nil
	}
	lines := strings.Split(string(src), "\n")
	var units []Unit
	add := func(kind string, a, b token.Pos, ctx string) {
		s, e := fset.Position(a).Line, fset.Position(b).Line
		if e > len(lines) {
			e = len(lines)
		}
		units = append(units, Unit{Kind: kind, File: path, Start: s, End: e, Text: strings.Join(lines[s-1:e], "\n"), Context: ctx})
	}

	units = append(units, goSkeleton(fset, f, path, lines))

	for _, d := range f.Decls {
		switch d := d.(type) {
		case *ast.FuncDecl:
			kind := "Function"
			if strings.HasPrefix(d.Name.Name, "Test") || strings.HasPrefix(d.Name.Name, "Fuzz") {
				kind = "TestFunction"
			}
			end := d.Type.End()
			if d.Body != nil {
				end = d.Body.End()
			}
			add(kind, d.Pos(), end, "")
			units[len(units)-1].name = goTopFuncName(d)
			if d.Doc != nil {
				units[len(units)-1].ContextStart = fset.Position(d.Doc.Pos()).Line
				units[len(units)-1].Context = strings.TrimSpace(d.Doc.Text())
			}
		case *ast.GenDecl:
			for _, spec := range d.Specs {
				ts, ok := spec.(*ast.TypeSpec)
				if ok && ts.Type != nil {
					if _, isIface := ts.Type.(*ast.InterfaceType); isIface {
						add("Interface", ts.Pos(), ts.Type.End(), "")
						if doc := specDoc(d, ts); doc != nil {
							units[len(units)-1].ContextStart = fset.Position(doc.Pos()).Line
							units[len(units)-1].Context = strings.TrimSpace(doc.Text())
						}
					}
				}
			}
		}
	}

	for _, g := range f.Comments {
		add("Comment", g.Pos(), g.End(), goCommentContext(fset, f, lines, g))
	}
	return units
}

func goTopFuncName(d *ast.FuncDecl) string {
	if d.Recv != nil {
		return ""
	}
	return d.Name.Name
}

// goSkeleton: one unit per Go file listing declarations with line numbers.
func goSkeleton(fset *token.FileSet, f *ast.File, path string, lines []string) Unit {
	sk := []string{fmt.Sprintf("file %s (lines 1-%d)", path, len(lines))}
	for _, d := range f.Decls {
		ln := fset.Position(d.Pos()).Line
		first := strings.TrimSpace(lines[ln-1])
		if len(first) > 120 {
			first = first[:120] + " …"
		}
		sk = append(sk, fmt.Sprintf("%d\t%s", ln, first))
	}
	return Unit{Kind: "File", File: path, Start: 1, End: len(lines), Text: strings.Join(sk, "\n")}
}

// specDoc: a lone spec in a parenthesis-free declaration inherits the declaration's doc.
func specDoc(d *ast.GenDecl, ts *ast.TypeSpec) *ast.CommentGroup {
	if ts.Doc == nil && len(d.Specs) == 1 {
		return d.Doc
	}
	return ts.Doc
}

// goCommentContext: a comment in or above a bounded declaration sees that
// declaration alone; directives keep +-8 lines so preceding rationales stay visible.
func goCommentContext(fset *token.FileSet, f *ast.File, lines []string, g *ast.CommentGroup) string {
	s, e := fset.Position(g.Pos()).Line, min(fset.Position(g.End()).Line, len(lines))
	if s >= 1 && s <= e && isSuppressionComment(Unit{Kind: "Comment", Text: strings.Join(lines[s-1:e], "\n")}) {
		return commentContext(lines, s, e)
	}
	for _, d := range f.Decls {
		start := d.Pos()
		if fd, ok := d.(*ast.FuncDecl); ok && fd.Doc != nil {
			start = fd.Doc.Pos()
		} else if gd, ok := d.(*ast.GenDecl); ok && gd.Doc != nil {
			start = gd.Doc.Pos()
		}
		ds, de := fset.Position(start).Line, min(fset.Position(d.End()).Line, len(lines))
		if ds <= s && e <= de && de-ds <= rawBudgetLines {
			if ctx := numberedContext(lines, ds, de, s, e); ctx != "" {
				return ctx
			}
		}
	}
	return commentContext(lines, s, e)
}

// Bounds on same-file helper bodies attached to a TestFunction's Context.
const (
	maxTestHelperLines = 30
	maxTestHelperTotal = 50
)

type testHelper struct {
	name  string
	lines int
	text  string
}

// attachTestHelpers adds short same-file helper functions called by a TestFunction
// into its Context so rules can see fake clocks and assertion helpers.
func attachTestHelpers(units []Unit) []Unit {
	var helpers []testHelper
	hasTest := false
	for _, u := range units {
		if u.Kind == "TestFunction" {
			hasTest = true
		} else if u.Kind == "Function" && u.End-u.Start+1 <= maxTestHelperLines && len(u.name) >= 3 {
			// skip 1-2 char names (e.g. f, fn) that collide with local variables
			helpers = append(helpers, testHelper{name: u.name, lines: u.End - u.Start + 1, text: numberedLines(u.Text, u.Start)})
		}
	}
	if !hasTest || len(helpers) == 0 {
		return units
	}
	for i := range units {
		if units[i].Kind == "TestFunction" {
			appendHelperContext(&units[i], helpers)
		}
	}
	return units
}

func appendHelperContext(u *Unit, helpers []testHelper) {
	var refs []string
	used := 0
	for _, h := range helpers {
		if !callsHelper(u.Text, h.name) || used+h.lines > maxTestHelperTotal {
			continue
		}
		refs = append(refs, h.text)
		used += h.lines
	}
	if len(refs) == 0 {
		return
	}
	block := "HELPERS IN THIS FILE:\n" + strings.Join(refs, "\n")
	if u.Context != "" {
		u.Context += "\n\n" + block
	} else {
		u.Context = block
	}
}

func numberedLines(text string, start int) string {
	ls := strings.Split(text, "\n")
	out := make([]string, 0, len(ls))
	for i, l := range ls {
		if strings.TrimSpace(l) == "" {
			continue
		}
		out = append(out, fmt.Sprintf("%d\t%s", start+i, l))
	}
	return strings.Join(out, "\n")
}

func callsHelper(body, name string) bool {
	for idx := 0; idx < len(body); {
		j := strings.Index(body[idx:], name)
		if j < 0 {
			return false
		}
		pos := idx + j
		end := pos + len(name)
		prevOK := pos == 0 || (!isIdentByte(body[pos-1]) && body[pos-1] != '.')
		nextOK := end < len(body) && body[end] == '('
		if prevOK && nextOK {
			return true
		}
		idx = pos + 1
	}
	return false
}

func isIdentByte(b byte) bool {
	return (b >= 'a' && b <= 'z') || (b >= 'A' && b <= 'Z') || (b >= '0' && b <= '9') || b == '_' || b == '$'
}

func splitMarkdown(path string, src []byte) []Unit {
	lines := strings.Split(string(src), "\n")
	var units []Unit
	fence := false
	i, n := frontMatterEnd(lines), len(lines)
	for i < n {
		t := strings.TrimSpace(lines[i])
		if strings.HasPrefix(t, "```") {
			fence = !fence
			i++
			continue
		}
		if fence || t == "" || strings.HasPrefix(t, "#") {
			i++
			continue
		}
		start, kind := i, mdKind(t)
		switch {
		case strings.HasPrefix(t, "|"): // table block: first-class unit; only table rules may apply
			i, kind = blockEnd(lines, i, func(l string) bool { return !strings.HasPrefix(strings.TrimSpace(l), "|") }), "Table"
		case isBullet(t):
			i = blockEnd(lines, i, func(l string) bool { return blockBreak(l) || (!isBullet(strings.TrimSpace(l)) && !isIndented(l)) })
		default:
			i = blockEnd(lines, i, func(l string) bool { return blockBreak(l) || isBullet(strings.TrimSpace(l)) })
		}
		units = append(units, Unit{Kind: kind, File: path, Start: start + 1, End: i, Text: strings.Join(lines[start:i], "\n")})
	}
	return addMarkdownStructure(path, lines, units)
}

// frontMatterEnd: the first line after YAML front matter, which is metadata, not prose.
func frontMatterEnd(lines []string) int {
	if len(lines) == 0 || strings.TrimSpace(lines[0]) != "---" {
		return 0
	}
	for i := 1; i < len(lines); i++ {
		if t := strings.TrimSpace(lines[i]); t == "---" || t == "..." {
			return i + 1
		}
	}
	return 0
}

// blockEnd: the first line from i that stops the block.
func blockEnd(lines []string, i int, stop func(string) bool) int {
	for i < len(lines) && !stop(lines[i]) {
		i++
	}
	return i
}

// blockBreak: a blank line, heading, or fence ends any prose block.
func blockBreak(l string) bool {
	t := strings.TrimSpace(l)
	return t == "" || strings.HasPrefix(t, "#") || strings.HasPrefix(t, "```")
}

// mdWholeLines caps Section and Document units, which are always sent whole.
// shortcut: longer ones are skipped, upgrade to an outline digest if big docs matter.
const mdWholeLines = 400

type mdHeading struct{ level, line int }

// addMarkdownStructure gives each block its heading path, previous block, and next line,
// and adds Section and Document units for sections and files under mdWholeLines.
func addMarkdownStructure(path string, lines []string, units []Unit) []Unit {
	heads, paths := headingPaths(lines)
	units = slices.DeleteFunc(units, notAuthorProse)
	header := docHeader(lines)
	for k := range units {
		u := &units[k]
		ctx := header + "\nHEADING: " + paths[u.Start]
		if k == 0 {
			ctx += "\nPOSITION: first block of the document"
		}
		if k > 0 && paths[units[k-1].Start] == paths[u.Start] {
			ctx += "\nPREVIOUS BLOCK:\n" + units[k-1].Text
		}
		if next := nextLine(lines, u.End); next != "" {
			ctx += "\nNEXT LINE: " + next
		}
		u.Context = ctx
	}
	prose := slices.DeleteFunc(slices.Clone(units), func(u Unit) bool { return u.Kind != "Paragraph" && u.Kind != "Bullet" && u.Kind != "Steps" })
	for _, u := range prose {
		units = append(units, candidateUnits(u, header, paths[u.Start])...)
		if m, ok := mixedList(u); ok && u.Kind != "Paragraph" {
			units = append(units, m)
		}
	}
	text := proseLines(lines)
	units = append(units, sectionUnits(path, text, heads, header)...)
	if len(units) > 0 && len(lines) < mdWholeLines {
		units = append(units, Unit{Kind: "Document", File: path, Start: 1, End: len(lines), Text: strings.Join(text, "\n"), Context: header})
	}
	return units
}

// proseLines blanks front matter and fenced code bodies while leaving a placeholder on each
// opening fence so Section/Document rules see that code exists without linting code as prose.
func proseLines(lines []string) []string {
	out := slices.Clone(lines)
	fence, meta := false, frontMatterEnd(lines)
	for i := range out {
		if i < meta {
			out[i] = ""
			continue
		}
		if strings.HasPrefix(strings.TrimSpace(out[i]), "```") {
			if fence {
				out[i] = ""
			} else {
				out[i] = fencePlaceholder(out[i])
			}
			fence = !fence
		} else if fence {
			out[i] = ""
		}
	}
	return out
}

func fencePlaceholder(line string) string {
	if fs := strings.Fields(strings.TrimLeft(strings.TrimSpace(line), "`")); len(fs) > 0 {
		return "[" + fs[0] + " code block]"
	}
	return "[code block]"
}

func isCodePlaceholder(t string) bool {
	if t == "[code block]" {
		return true
	}
	inner, ok := strings.CutPrefix(t, "[")
	if !ok {
		return false
	}
	lang, ok := strings.CutSuffix(inner, " code block]")
	return ok && lang != "" && !strings.ContainsAny(lang, " \t")
}

// headingPaths: the headings outside code fences, and the "A > B" heading path in force at each line.
func headingPaths(lines []string) ([]mdHeading, []string) {
	var heads []mdHeading
	paths := make([]string, len(lines)+1)
	var stack []string
	fence := false
	for i, l := range lines {
		t := strings.TrimSpace(l)
		if strings.HasPrefix(t, "```") {
			fence = !fence
		}
		if lvl := len(t) - len(strings.TrimLeft(t, "#")); !fence && lvl > 0 && lvl <= 6 && strings.HasPrefix(t[lvl:], " ") {
			heads = append(heads, mdHeading{lvl, i + 1})
			stack = append(stack[:min(len(stack), lvl-1)], strings.TrimSpace(t[lvl:]))
			for len(stack) < lvl {
				stack = append([]string{""}, stack...)
			}
		}
		paths[i+1] = strings.Join(slices.DeleteFunc(slices.Clone(stack), func(x string) bool { return x == "" }), " > ")
	}
	return heads, paths
}

// notAuthorProse: comment-only blocks, rules (---), and blockquotes (quoted speech, callouts).
func notAuthorProse(u Unit) bool {
	t := strings.TrimSpace(htmlComment.ReplaceAllString(u.Text, ""))
	return t == "" || strings.Trim(t, "-*_ ") == "" || !slices.ContainsFunc(strings.Split(t, "\n"), func(l string) bool { return !strings.HasPrefix(strings.TrimSpace(l), ">") })
}

func nextLine(lines []string, from int) string {
	for j := from; j < len(lines); j++ {
		if t := strings.TrimSpace(lines[j]); t != "" {
			return t
		}
	}
	return ""
}

// sectionUnits: one unit per filled H2+ section, up to the next heading at its level or above.
// lines has code blanked, so a section that is only a fenced block reads as a placeholder: nothing to judge.
func sectionUnits(path string, lines []string, heads []mdHeading, header string) []Unit {
	var units []Unit
	for k, h := range heads {
		if h.level < 2 {
			continue
		}
		end := len(lines)
		if n := slices.IndexFunc(heads[k+1:], func(n mdHeading) bool { return n.level <= h.level }); n >= 0 {
			end = heads[k+1+n].line - 1
		}
		for end > h.line && strings.TrimSpace(lines[end-1]) == "" {
			end--
		}
		if end > h.line && end-h.line < mdWholeLines && !placeholderBody(lines[h.line:end]) {
			units = append(units, Unit{Kind: "Section", File: path, Start: h.line, End: end, Text: strings.Join(lines[h.line-1:end], "\n"), Context: header})
		}
	}
	return units
}

// mdKind: a list starting "1." is Steps, kept distinct from Bullet for list-parallelism and prose rules.
func mdKind(first string) string {
	switch {
	case !isBullet(first):
		return "Paragraph"
	case first[0] >= '0' && first[0] <= '9':
		return "Steps"
	}
	return "Bullet"
}

var htmlComment = regexp.MustCompile(`(?s)<!--.*?-->`)

// docHeader: the title and status every Markdown unit is judged against.
func docHeader(lines []string) string {
	title, status := "", ""
	if len(lines) > 0 && strings.TrimSpace(lines[0]) == "---" {
		for _, l := range lines[1:] {
			t := strings.TrimSpace(l)
			if t == "---" || t == "..." {
				break
			}
			if k, v, ok := strings.Cut(t, ":"); ok {
				switch strings.ToLower(k) {
				case "title":
					title = strings.Trim(strings.TrimSpace(v), `"'`)
				case "status":
					status = strings.Trim(strings.TrimSpace(v), `"'`)
				}
			}
		}
	}
	for _, l := range lines {
		if t := strings.TrimSpace(l); title == "" && strings.HasPrefix(t, "# ") {
			title = strings.TrimSpace(t[2:])
		}
	}
	h := "DOCUMENT TITLE: " + title
	if status != "" {
		h += "\nDOCUMENT STATUS: " + status
	}
	return h
}

func isBullet(t string) bool {
	for _, p := range []string{"- ", "* ", "+ "} {
		if strings.HasPrefix(t, p) {
			return true
		}
	}
	// numbered list: "1. " or "1) "
	if len(t) >= 2 && t[0] >= '0' && t[0] <= '9' {
		for j := 1; j < len(t); j++ {
			if t[j] == '.' || t[j] == ')' {
				return j+1 < len(t) && t[j+1] == ' '
			}
			if t[j] < '0' || t[j] > '9' {
				return false
			}
		}
	}
	return false
}

func isIndented(line string) bool {
	return len(line) > 0 && (line[0] == ' ' || line[0] == '\t')
}

// contentFor picks what a whole-scope rule sees for an oversized unit: a
// line-numbered digest of signature/branch/assert/return lines. Local rules
// get raw windows instead (see lint.go).
func digestFor(u Unit, lines []string) string {
	var out []string
	for ln := u.Start; ln <= u.End; ln++ {
		raw := lines[ln-1]
		s := strings.TrimSpace(raw)
		if s == "" {
			continue
		}
		keep := ln <= u.Start+2
		if !keep {
			kw := strings.TrimSpace(strings.TrimPrefix(s, "}"))
			switch {
			case strings.HasPrefix(kw, "if "), strings.HasPrefix(kw, "if("),
				strings.HasPrefix(kw, "else "),
				strings.HasPrefix(kw, "switch "), strings.HasPrefix(kw, "switch("),
				strings.HasPrefix(kw, "for "), strings.HasPrefix(kw, "for("),
				strings.HasPrefix(kw, "while "), strings.HasPrefix(kw, "while("),
				strings.HasPrefix(kw, "try "), strings.HasPrefix(kw, "try{"), strings.HasPrefix(kw, "try:"),
				strings.HasPrefix(kw, "catch "), strings.HasPrefix(kw, "catch("), strings.HasPrefix(kw, "catch{"),
				strings.HasPrefix(kw, "except "), strings.HasPrefix(kw, "except:"),
				strings.HasPrefix(kw, "throw "), strings.HasPrefix(kw, "raise "),
				strings.HasPrefix(kw, "return "), strings.HasPrefix(kw, "defer "), strings.HasPrefix(kw, "go "),
				strings.Contains(s, "assert."), strings.Contains(s, "assert("), strings.Contains(s, "expect("),
				strings.Contains(s, "require."),
				strings.Contains(s, "t.Error"), strings.Contains(s, "t.Fatal"), strings.Contains(s, "t.Log"):
				keep = true
			}
		}
		if keep {
			out = append(out, fmt.Sprintf("%d\t%s", ln, strings.TrimRight(raw, " \t")))
		}
	}
	return strings.Join(out, "\n")
}

var (
	commentMarker = regexp.MustCompile(`^\s*(//+|#+|/\*+|\*+/?|--|;+|<!--|\{\s*/\*+)\s?`)
	ruleLine      = regexp.MustCompile(`^[^\p{L}\p{N}]{3,}$`)
	toolDirective = regexp.MustCompile(`^(?:shellcheck|eslint|prettier-ignore|@ts-|nolint|NOLINT|noqa|go:\S|lint:\S|lintdec:ignore|pylint|type:\s*ignore|istanbul|c8 |biome-ignore|ktlint|tslint|jshint|NOSONAR|region|endregion)`)
	// toolDirectiveAnyCase includes non-suppression directives like rubocop:enable so they drop as structural;
	// suppressionAnyCase includes only disable/noqa forms that route to suppression-no-reason.
	toolDirectiveAnyCase = regexp.MustCompile(`(?i)^(?:ruff:\s*noqa|flake8:\s*noqa|pragma\s+warning\s+disable|markdownlint-disable|rubocop:(?:disable|enable))`)
	suppressionDirective = regexp.MustCompile(`^(?:eslint-disable|@ts-ignore|@ts-expect-error|nolint|NOLINT|noqa|type:\s*ignore|biome-ignore|pylint:\s*disable|ktlint-disable|NOSONAR|istanbul ignore|c8 ignore|shellcheck disable)`)
	suppressionAnyCase   = regexp.MustCompile(`(?i)^(?:ruff:\s*noqa|flake8:\s*noqa|pragma\s+warning\s+disable|markdownlint-disable|rubocop:disable)`)
)

func isToolDirective(t string) bool {
	return toolDirective.MatchString(t) || toolDirectiveAnyCase.MatchString(t)
}

func isSuppressionComment(u Unit) bool {
	if u.Kind != "Comment" {
		return false
	}
	for line := range strings.SplitSeq(u.Text, "\n") {
		t := strings.TrimSpace(commentMarker.ReplaceAllString(line, ""))
		if suppressionDirective.MatchString(t) || suppressionAnyCase.MatchString(t) {
			return true
		}
	}
	return false
}

// precedingRationale returns contiguous non-directive comment lines immediately above u.Start
// from numbered Context so preceding ShellCheck/Go/Python rationales travel in TARGET.
func precedingRationale(u Unit) string {
	if u.Start <= 1 || u.Context == "" {
		return ""
	}
	byLine := map[int]string{}
	for raw := range strings.SplitSeq(u.Context, "\n") {
		numStr, body, ok := strings.Cut(raw, "\t")
		if !ok {
			continue
		}
		var ln int
		if _, err := fmt.Sscanf(numStr, "%d", &ln); err == nil {
			byLine[ln] = body
		}
	}
	var lead []string
	for ln := u.Start - 1; ln >= 1; ln-- {
		body, ok := byLine[ln]
		if !ok {
			break
		}
		trimmed := strings.TrimSpace(body)
		if strings.HasPrefix(trimmed, "#!") || !commentMarker.MatchString(body) {
			break
		}
		inner := strings.TrimSpace(commentMarker.ReplaceAllString(body, ""))
		if inner == "" || ruleLine.MatchString(inner) || isToolDirective(inner) {
			break
		}
		lead = append(lead, body)
	}
	if len(lead) == 0 {
		return ""
	}
	slices.Reverse(lead)
	return strings.Join(lead, "\n")
}

// filterComments filters units in place: pure suppression directives become Directive units,
// other structural banners/directives are dropped, and prose (including mixed prose+directive blocks) stays Comment.
func filterComments(units []Unit) []Unit {
	out := units[:0]
	for _, u := range units {
		if structuralComment(u) {
			if isSuppressionComment(u) {
				u.Kind = "Directive"
				if lead := precedingRationale(u); lead != "" {
					u.Text = lead + "\n" + u.Text
				}
				out = append(out, u)
			}
			continue
		}
		out = append(out, u)
	}
	return out
}

// structuralComment: section banners and tool directives look like comments but say nothing to lint,
// and Jev flags them as tautologies.
func structuralComment(u Unit) bool {
	if u.Kind != "Comment" {
		return false
	}
	var rules, directives, titles int
	for _, line := range strings.Split(u.Text, "\n") {
		t := strings.TrimSpace(commentMarker.ReplaceAllString(line, ""))
		switch {
		case t == "" || ruleLine.MatchString(t):
			rules++
		case isToolDirective(t):
			directives++
		case len(strings.Fields(t)) <= 5:
			titles++
		default:
			return false
		}
	}
	return directives > 0 || (rules > 0 && titles <= 1 && strings.TrimSpace(u.Text) != "")
}

// placeholderLine: a line that only says the content is missing ("TBD", "N/A", "TODO: ABC-123").
var placeholderLine = regexp.MustCompile(`(?i)^[-*+_(\s]*(tbd|tba|todo|n/?a|wip|coming soon|to be (?:determined|added|written))\b[\s.:!)*_-]*(?:[a-z]+-\d+)?[\s.)*_]*$`)

// placeholderBody: an unfilled template section (comments, empty tables, sub-headings only) has nothing to judge yet.
func placeholderBody(body []string) bool {
	text := htmlComment.ReplaceAllString(strings.Join(body, "\n"), "")
	header := true
	for _, l := range strings.Split(text, "\n") {
		t := strings.TrimSpace(l)
		switch {
		case strings.Trim(t, "-*+ ") == "", strings.HasPrefix(t, "#"), placeholderLine.MatchString(t), isCodePlaceholder(t): // blank, bare bullet, heading, TBD, or code block
		case strings.HasPrefix(t, "|"):
			if strings.Trim(t, "|-: ") == "" {
				header = false // separator row; rows after it are data
			} else if !header && strings.Trim(t, "| ") != "" {
				return false
			}
		default:
			return false
		}
	}
	return true
}
